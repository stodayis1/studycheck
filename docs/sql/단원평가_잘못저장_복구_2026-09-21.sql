-- 2026-09-21에 「입학테스트」로 잘못 저장된 초6 단원평가 6건을 제자리로 옮긴다
--
-- 무슨 일이 있었나:
--   평가관리 화면은 열면 항상 「입학테스트」 탭이 기본(useState<ExamType>('입학테스트'))이고,
--   저장할 때 exam_type을 **그때 열려 있던 탭**으로 넣는다(exam_type: tab). 모달 안에는 평가 종류를
--   고르는 칸이 없었다. 그래서 휴대폰처럼 탭 카드가 스크롤로 사라진 화면에서 헤더의
--   「+ 평가 등록」만 눌러 입력하면 전부 입학테스트로 저장된다.
--   → 데이터가 날아간 게 아니라 다른 칸에 들어간 것이다.
--
-- 대상 6건 (2026-09-21 18:22~18:23, 입력자 윤지혜, 전원 초6, 범위 'Ⅰ 분수의 나눗셈'):
--   안준혁 93 / 오현승 100 / 유정환 95 / 임지원 100 / 최다빈 95 / 홍채은 90
--   여섯 명 모두 최초 평가일이 5월이라 신규생이 아니다(입학테스트일 수 없다).
--
-- 초6 2학기 1단원 = 'Ⅰ 분수의 나눗셈' (concepts 확인). 화면 저장 규칙대로 로마숫자를 뗀
-- '분수의 나눗셈'을 unit_name에 넣는다 — 그래야 단원평가 현황판/학생 카드 그리드에 잡힌다.
--
-- ⚠️ 안준혁은 9/22에 같은 2학기 1단원이 100점으로 한 건 더 들어가 있다(19:17 입력).
--    이 파일을 돌리면 93점과 100점 두 건이 된다. 현황판은 날짜가 늦은 9/22(100점)를 보여준다.
--    어느 쪽이 맞는지는 원장님만 아시므로 여기서 지우지 않는다. 정리하려면 맨 아래 주석 참고.
--
-- 되돌리기: 아래 UPDATE를 그대로 두고 set 부분만
--   exam_type='입학테스트', title=null, unit=null, unit_name='Ⅰ 분수의 나눗셈', semester=null
--   로 바꿔 다시 실행하면 원상복구된다. 행을 지우지 않으므로 점수는 어떤 경우에도 남는다.

begin;

-- 바꾸기 전 확인 (실행하면 6줄이 나와야 한다)
select s.name, s.grade, e.exam_type, e.unit_name, e.score, e.exam_date
from exams e join students s on s.id = e.student_id
where e.id in (
  'd9786d27-245e-4e91-998c-b2196d06d1c5',  -- 안준혁 93
  '75fd6444-dd29-4b86-b123-157673a81f20',  -- 오현승 100
  '4cdacd7c-cebf-4918-8332-3df5c19e25a1',  -- 유정환 95
  '9d10d85e-6fc0-4477-b48f-a470b62f8709',  -- 임지원 100
  'aeffaf6d-1fea-44fe-a2a4-1253e2cebb70',  -- 최다빈 95
  '90f65539-fed7-48b8-bfca-d9ce43478daf'   -- 홍채은 90
);

update exams set
  exam_type = '학교시험',
  title     = '단원평가',
  unit      = '1단원',
  unit_name = '분수의 나눗셈',
  semester  = 2
where id in (
  'd9786d27-245e-4e91-998c-b2196d06d1c5',
  '75fd6444-dd29-4b86-b123-157673a81f20',
  '4cdacd7c-cebf-4918-8332-3df5c19e25a1',
  '9d10d85e-6fc0-4477-b48f-a470b62f8709',
  'aeffaf6d-1fea-44fe-a2a4-1253e2cebb70',
  '90f65539-fed7-48b8-bfca-d9ce43478daf'
);

commit;

