-- 매쓰홀릭 동명이인 규칙을 더한다. (원장님 2026-11-06)
--   「이지훈은 초5학년 맞아」 · 「박시연2는 박경미 쌤 맞아」
--
-- 왜
--   매쓰홀릭 이름 하나에 스터디체크 학생이 둘 걸리면 화면이 멈추고 사람이 매번 골라야 한다.
--     · 이지훈   — 스터디체크에 둘(초5 조윤희T · 고1 윤지혜T). 매쓰홀릭에서 고1 쪽은
--                  「이지훈h」로 적고 그 규칙은 이미 있다. 꼬리 없는 「이지훈」이 초5다.
--     · 박시연2  — 스터디체크에 「박시연2」(중2 박경미T)가 따로 있고, 꼬리를 뗀
--                  「박시연」(중2 신애진T)도 있어서 둘 다 후보로 걸린다. 박경미T 쪽이다.
--   2026-11-06 하루분 91건 중 이 둘 때문에 4건이 멈췄다.
--
-- 값은 **담당 강사 이름**이다 (학생 id 가 아니다 — 학생 id·점수를 저장소에 넣지 않는다).
-- 규칙으로 골라도 화면에는 「규칙으로 골랐어요」라고 적히고 선생님이 바꿀 수 있다.
--
-- 되돌리기: 매쓰홀릭_동명이인_되돌리기.sql

update public.app_settings
set value = value || '{"이지훈": "조윤희", "박시연2": "박경미"}'::jsonb,
    updated_at = now()
where key = 'matholic_name_rules';

-- 확인 — 이수연·유연우2·이지훈h 는 그대로 있고 두 줄이 더해졌는지 본다
select value from public.app_settings where key = 'matholic_name_rules';
