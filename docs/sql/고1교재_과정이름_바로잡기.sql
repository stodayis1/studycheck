-- 「고1」로 등록된 교재 7권을 **과정 이름**(공통수학1·공통수학2)으로 바로잡는다 (2026-11-05)
-- 되돌리기: 고1교재_과정이름_바로잡기_되돌리기.sql
--
-- 왜 (원장님 2026-11-05 「고1 개념 목록 넣어주고」)
--   월간보고서 진도율이 안 잡히는 교재 7권이 전부 grade='고1' 이었다. 그런데 이 앱의 고등은
--   **학년이 아니라 과정 이름**으로 돈다 — concepts 에 있는 고등 과정은
--   공통수학1(34) · 공통수학2(29) · 대수(24) · 미적분1(17) · 확률과통계(16) · 기하(21) 뿐이고
--   「고1」은 없다. 과정관리 화면의 고등 선택지도 이 여섯 개뿐이다.
--
--   그래서 「고1 개념 목록」을 새로 만들면 **같은 단원이 두 벌**이 되고, 이미 공통수학1·2 로
--   쌓인 개념 체크와 갈린다. 고쳐야 할 것은 개념 목록이 아니라 **교재 7권의 과정 이름**이다.
--
-- ★ 교재 id 로 한 줄씩 고친다. 「grade='고1' 전부」로 고치지 않는다 — 나중에 또 생긴 줄까지
--   휩쓸면 안 된다.
-- ★ 개념 체크(progress_checks)는 건드리지 않는다. 과정 이름만 바뀐다.
-- ★ 7권 중 **재원 중인 학생 것은 한 권**(아래 ①의 둘째 줄)이다. 나머지 여섯 권은 퇴원 학생
--   기록이라 보고서에 안 나간다 — 기록을 맞춰 두는 것뿐이다.

begin;

-- ① 근거가 분명한 것
--   공통수학1 개념 34개를 이미 **전부** 체크해 둔 학생의 개념서 (교재 구분이 없던 예전 기록)
update public.student_textbooks set grade = '공통수학1'
 where id = 'c53ae742-8c6f-469f-96ea-0b40db4a7a2f' and grade = '고1';
--   짝 교재가 「공통수학2-1 개념+유형」이고 공통수학2 개념 체크가 12개 있는 학생의 유형서
update public.student_textbooks set grade = '공통수학2'
 where id = 'b5cac79e-79fe-4a4b-85b0-0c3881d47849' and grade = '고1';

-- ② 2026년 6월(고1 1학기)에 배정된 것 — 그때 과정은 공통수학1이다. (전부 퇴원 학생)
update public.student_textbooks set grade = '공통수학1'
 where id in (
   '41bb14cf-9e0c-447e-a1b7-d7be770e8c01',   -- 개념서 2026-06-03
   'dae793ed-2c5d-429c-806b-9397753ce1d6',   -- 유형서 2026-06-04
   '240c1407-3609-4b97-9de0-ad9c82440f6d',   -- 개념서 2026-06-03
   '63eaf90d-432b-403f-9d53-71748d633a71',   -- 유형서 2026-06-04
   '81103a95-925e-4573-81f8-e8f061dd6f5e'    -- 개념서 2026-06-03
 ) and grade = '고1';

commit;

