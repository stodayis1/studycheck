-- 매쓰홀릭 동명이인 규칙에 「이지훈」을 더한다. (원장님 2026-11-06 「이지훈은 초5학년 맞아」)
--
-- 왜
--   스터디체크에 「이지훈」이 둘이다 — 초5(조윤희T) · 고1(윤지혜T).
--   매쓰홀릭에서 고1 쪽은 꼬리를 붙여 「이지훈h」로 적고(이미 규칙에 있다),
--   꼬리 없는 「이지훈」이 누구인지는 규칙이 없어서 매번 사람이 골라야 했다.
--   실제로 2026-11-06 하루분 91건 중 2건이 그래서 멈췄다.
--
-- 값은 **담당 강사 이름**이다 (학생 id 가 아니다 — 학생 실명·id 를 저장소에 넣지 않는다).
-- 규칙으로 골라도 화면에는 「규칙으로 골랐어요」라고 적히고 선생님이 바꿀 수 있다.
--
-- 되돌리기: 매쓰홀릭_동명이인_이지훈_되돌리기.sql

update public.app_settings
set value = value || '{"이지훈": "조윤희"}'::jsonb,
    updated_at = now()
where key = 'matholic_name_rules';

-- 확인
select value from public.app_settings where key = 'matholic_name_rules';
