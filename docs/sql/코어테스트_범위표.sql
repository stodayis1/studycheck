--
-- ★ 담을 곳이 지금까지 없었다. `core_tests` 는 학생별 **점수**를 담던 옛 표라 다르다
--   (지금 점수는 exams.exam_type='코어테스트' 로 들어간다).
-- ★ 범위는 학생 것이 아니라 **학원 공통**이다 — 학생 수만큼 늘지 않는다(한 해 108줄).
-- ★ 여러 단원이면 한 칸 안에 **줄바꿈**으로 넣는다. 화면에서 그대로 줄을 나눠 보여 준다.
--
-- 들어가는 범위 (원장님이 주신 표 그대로 옮겨 적었다 — 눈으로 읽고 기계 판독으로 한 번 더 대조)
--   · 초등 1~6학년 · 중등 1~3학년 · 2026-03-20 ~ 2027-02-20 매달 20일
--   · 초1 2026-03-20 은 표에 「-」(시험 없음)이라 **줄을 안 넣는다**
--   · 고등은 아직 안 받았다 — 받으면 같은 모양으로 덧붙인다

begin;

create table if not exists public.core_test_ranges (
  id         uuid primary key default gen_random_uuid(),
  test_date  date not null,                    -- 시행일 (매달 20일)
  grade      text not null,                    -- '초1'…'초6', '중1'…'중3' (students.grade 와 같은 말)
  scope      text not null,                    -- 범위. 여러 줄이면 줄바꿈
  created_at timestamptz not null default now(),
  unique (test_date, grade)
);
create index if not exists core_test_ranges_date on public.core_test_ranges (test_date);

alter table public.core_test_ranges enable row level security;

-- 쓰기는 직원만. (select ...) 로 감싸야 줄마다 다시 안 돈다.
drop policy if exists staff_all on public.core_test_ranges;
create policy staff_all on public.core_test_ranges for all
  using ((select public.is_staff())) with check ((select public.is_staff()));

-- ★ 읽기는 **로그인한 사람 모두**에게 연다 — 학생·학부모도 본인 시험 범위를 봐야 한다.
--   보통은 `to authenticated using (true)` 가 위험하지만(학생도 익명 authenticated 다),
--   이 표에는 **개인정보가 한 줄도 없다** — 학원 공통 시험범위뿐이다. 일부러 연 것이다.
drop policy if exists everyone_read on public.core_test_ranges;
create policy everyone_read on public.core_test_ranges for select to authenticated
  using (true);

