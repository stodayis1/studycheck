-- 학부모 브리핑 저녁 발송을 **밤 9시**로 늦힌다 (원장님 2026-11-17)
--
-- 왜
--   초등 선생님들이 매쓰홀릭 점수를 붙여넣는 것이 저녁 8시 발송보다 늦어, 그날 친
--   코어테스트·학습지 점수가 학부모님께 영영 안 나가는 일이 있었다.
--     2026-11-17 이온유(초2) — 20:00:47 발송 → 20:11:15 점수 입력.
--     「▶ 학습 결과」에 과제 성취도만 적혀 나갔고, 코어테스트 91점과 학습지 3장은 빠졌다.
--   선생님들이 8시에 퇴근하시므로 9시면 그날 것이 다 차 있다.
--
-- ★ 이 한 줄이 **코드보다 먼저** 적용돼야 한다.
--   라우트(lib/cronBriefing.ts)는 평일 21:00 전이면 그냥 돌아간다. 깨움이 20:50 에
--   끝나는 지금 상태에서 코드만 배포되면 **그날 저녁 발송이 통째로 안 나간다**.
--   반대로 이 줄만 먼저 적용하는 것은 **아무것도 바꾸지 않는다** — 21:00~21:50 에
--   더 깨워 봐야 라우트가 「아직 20:00… 아니라 이미 돌았어요」로 돌려보낸다.
--
-- 되돌리기: docs/sql/브리핑_저녁발송_9시_되돌리기.sql

-- 저녁 깨움 창을 UTC 08:00~11:50(한국 17:00~20:50) → UTC 08:00~12:50(한국 17:00~21:50)
select cron.schedule('briefing-evening', '*/10 8-12 * * *', $$select public.wake_briefing('evening')$$);

-- 확인 — briefing-evening 이 '*/10 8-12 * * *' 이고 active 여야 한다
select jobid, jobname, schedule, active, username from cron.job order by jobid;
