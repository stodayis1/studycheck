/** 걸린 규칙들 (없으면 빈 배열) */
export function forbiddenWarnings(...texts: (string | null | undefined)[]): string[] {
  const hay = texts.filter(Boolean).join(' ')
  if (!hay.trim()) return []
  const out: string[] = []
  for (const f of FORBIDDEN) if (f.re.test(hay) && !out.includes(f.why)) out.push(f.why)
  return out
}

/** 글자 수 — 교육정보시스템은 Byte 로 세고 한글 1자는 3Byte 다 */
export function letterCount(s: string | null | undefined): { letters: number; bytes: number } {
  const t = String(s ?? '')
  let bytes = 0
  for (const ch of t) bytes += /[\0-\x7F]/.test(ch) ? 1 : 3
  return { letters: [...t].length, bytes }
}
