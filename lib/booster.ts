/** 전화번호 — 숫자만 남긴다. 중복은 이 값으로 가른다(010-1234-5678 과 01012345678 은 한 사람). */
export const 숫자만 = (s: unknown): string => String(s ?? '').replace(/\D/g, '')

/**
 * 쓸 만한 휴대폰 번호인가 — 010 으로 시작하는 11자리, 또는 10~11자리 숫자.
 * ★ 너무 깐깐하면 진짜 신청을 막는다. 선착순 1초가 걸린 화면이라 **되돌릴 수 없다.**
 */
export function 쓸만한번호인가(v: unknown): boolean {
  const d = 숫자만(v)
  return d.length === 10 || d.length === 11
}

/** 보기 좋게 — 010-1234-5678 */
export function 번호꼴(v: unknown): string {
  const d = 숫자만(v)
  if (d.length === 11) return `${d.slice(0, 3)}-${d.slice(3, 7)}-${d.slice(7)}`
  if (d.length === 10) return `${d.slice(0, 3)}-${d.slice(3, 6)}-${d.slice(6)}`
  return String(v ?? '')
}

export type 접수상태 = '접수전' | '접수중' | '마감'

/**
 * 지금 신청을 받을 수 있나.
 *
 * @param now     지금 (서버에서 부를 때는 서버 시각)
 * @param 나간자리 이미 나간 자리 수 — **취소해도 줄지 않는다.**
 *                원장님이 「자리 다시 열기」를 눌러야 준다 (자동 재오픈 안 함).
 */
export function 접수상태보기(입력: {
  now: Date
  나간자리: number
  정원?: number
  접수시작?: Date
}): 접수상태 {
  const 정원 = 입력.정원 ?? BOOSTER.정원
  const 시작 = 입력.접수시작 ?? new Date(BOOSTER.접수시작ISO)
  if (입력.now.getTime() < 시작.getTime()) return '접수전'
  if (입력.나간자리 >= 정원) return '마감'
  return '접수중'
}

/** 남은 자리 — 음수가 나오지 않게 */
export function 남은자리(나간자리: number, 정원: number = BOOSTER.정원): number {
  return Math.max(0, 정원 - Math.max(0, 나간자리 || 0))
}

/**
 * 접수 시작까지 남은 시간 — 화면 카운트다운에 쓴다.
 * 이미 지났으면 null (「0일 0:00:00」을 계속 보여 주지 않는다).
 */
export function 남은시간(now: Date, 시작: Date = new Date(BOOSTER.접수시작ISO)) {
  const ms = 시작.getTime() - now.getTime()
  if (ms <= 0) return null
  const 초 = Math.floor(ms / 1000)
  return {
    일: Math.floor(초 / 86400),
    시: Math.floor((초 % 86400) / 3600),
    분: Math.floor((초 % 3600) / 60),
    초: 초 % 60,
  }
}

/**
 * 신청서 한 장을 본다 — **화면과 서버가 같은 함수를 쓴다.**
 * 틀린 것이 없으면 빈 배열.
 *
 * ★ 화면에서만 검사하면 주소로 바로 찔러 넣을 수 있다. 서버도 이걸 부른다.
 */
export function 신청서검사(f: {
  student_name?: unknown
  grade?: unknown
  parent_name?: unknown
  parent_phone?: unknown
  is_enrolled?: unknown
  agreements?: unknown
}): string[] {
  const 틀림: string[] = []
  const 글 = (v: unknown) => String(v ?? '').trim()

  if (!글(f.student_name)) 틀림.push('학생 이름을 적어 주세요.')
  else if (글(f.student_name).length > 20) 틀림.push('학생 이름이 너무 깁니다.')

  if (!글(f.grade)) 틀림.push('학년을 골라 주세요.')
  else if (!(학년보기 as readonly string[]).includes(글(f.grade))) 틀림.push('학년을 골라 주세요.')

  if (!글(f.parent_name)) 틀림.push('학부모님 이름을 적어 주세요.')
  else if (글(f.parent_name).length > 20) 틀림.push('학부모님 이름이 너무 깁니다.')

  if (!글(f.parent_phone)) 틀림.push('학부모님 연락처를 적어 주세요.')
  else if (!쓸만한번호인가(f.parent_phone)) 틀림.push('연락처를 다시 확인해 주세요. (예: 010-1234-5678)')

  // ★ 재원 여부는 **묻지 않는다** (원장님 2026-11-21 「부스터는 재원생 대상」).
  //   누구나 「네」를 누를 수 있으므로, DB 함수 booster_apply() 가 학생 이름 + 등록 번호로
  //   students 를 찾아 본다 (docs/sql/부스터특강_재원생만.sql). 여기서는 보지 않는다.

  // ★ 동의는 **전부** 받아야 한다. 개수로 센다 — 화면만 고쳐 빠져나가지 못하게.
  const 동의 = Array.isArray(f.agreements) ? f.agreements.map(Boolean) : []
  if (동의.length !== 동의항목.length || !동의.every(Boolean)) {
    틀림.push('신청 전 확인 세 가지에 모두 동의해 주세요.')
  }

  return 틀림
}
