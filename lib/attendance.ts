// DB 에 CHECK 제약이 없으니(2026-10-08 확인) 코드가 유일한 기준이다.
// 문자열을 손으로 적지 말고 여기 상수를 쓸 것. 한 글자만 달라도 조용히 안 맞는다.

/**
 * 중·고등 학교 시험기간에 학원을 안 나온 날.
 * 결석률에 세지 않고, 보강을 잡지 않고(OPS 보강명단엔 「보강 안 함」으로 올라간다),
 * 학부모 카톡 브리핑도 보내지 않는다.
 */
export const ATT_EXAM = '시험기간 결석'

/**
 * 시험기간 결석인가?
 *
 * 2026-10-08 에 「시험기간」 → 「시험기간 결석」로 이름을 바꿨다(버튼 이름이 직관적이어야 한다는
 * 원장님 말씀). learning_notes 7건은 옮겼지만 report_links 의 jsonb 스냅샷은 **찍힌 그 순간의
 * 글자가 얼어 있어서** 바꿀 수 없다. 그래서 옛 이름도 같이 받아 준다.
 */
export const isExamAbsence = (v?: string | null) => v === ATT_EXAM || v === '시험기간'
