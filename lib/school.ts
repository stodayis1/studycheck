// 학교 이름 통일.
//
// 왜 필요한가 — 선생님마다 「신원중」과 「신원중학교」를 섞어 적어서 같은 학교가 두 줄로 갈라졌다.
// 시험대비 화면은 `students.school === exam_schedule.school_name` 으로 대상 학생을 찾는데,
// 「신원중학교」로 저장된 학생은 「신원중」 시험일정에 **영원히 안 걸린다.**
// 2026-10-08 기준 그렇게 어긋난 학생이 12명이었다(신원초등학교 7·신원중학교 2·고양초등학교 1·
// 백양고등학교 1·고양동산고등학교 1).
//
// 규칙 — 공식 명칭의 꼬리(초등학교·중학교·고등학교)를 줄임말(초·중·고)로 바꾼다.
// 저장하는 **모든** 자리(신규 등록·수정·엑셀 업로드·시험일정 등록)가 이 함수를 거친다.
// 그래야 원장님이 어느 쪽으로 적어도 알아서 한 가지로 모인다.

/** 꼬리만 자르면 안 되는 학교 — 줄임말이 아예 다른 경우 */
const ALIAS: Record<string, string> = {
  // 공식 명칭이 「고양오금초등학교」다. 「오금초」로 적힌 학생이 3명 있어 같은 학교가 둘로 갈려 있었다.
  오금초: '고양오금초',
}

export function normalizeSchool(raw?: string | null): string {
  // 공백은 아예 없앤다 — 「고양 오금초」처럼 중간에 띄어 쓰는 사람이 있다.
  let s = (raw ?? '').trim().replace(/\s+/g, '')
  if (!s) return ''
  s = s
    // 여자중·여자고는 「여중·여고」가 통례다. 꼬리 규칙보다 먼저 봐야 한다
    // (안 그러면 「○○여자중학교」가 「○○여자중」이 된다).
    .replace(/여자중학교$/, '여중')
    .replace(/여자고등학교$/, '여고')
    .replace(/초등학교$/, '초')
    .replace(/중학교$/, '중')
    .replace(/고등학교$/, '고')
    // 학년이 뒤에 붙어 들어온 것 — 실제로 「신원초6」, 「오금초 5」가 있었다(퇴원생 2명).
    // 학교 이름이 초·중·고 + 숫자로 끝나는 경우는 없으니 안전하다.
    .replace(/(초|중|고)[1-6]$/, '$1')
  return ALIAS[s] ?? s
}
