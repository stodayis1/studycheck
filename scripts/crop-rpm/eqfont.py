"""한글(HWP) 수식 폰트(HyhwpEQ) 글자 → 보통 글자 대응표.

이 교재(개념원리 RPM, 한글에서 뽑은 PDF)는 수식을 전용 폰트로 그린다.
그래서 PDF 글자층에는 \ue034 같은 **사용자 영역 글자**로 들어가 있고,
그냥 읽으면 숫자가 통째로 빠진다(「31) 답. 약수: , , , ,」처럼).

9개 파일에 쓰인 글자는 71가지뿐이라 전부 그려서 한 번에 읽어 적었다.
확인: 72의 약수 답이 \ue034,\ue035,\ue036,\ue037,\ue039,\ue03b,\ue03c,… →
      1,2,3,4,6,8,9,… 로 정확히 맞았다.
"""

EQ = {
    0xE000: 'A', 0xE001: 'B', 0xE002: 'C', 0xE003: 'D', 0xE006: 'G',
    0xE00B: 'L', 0xE00C: 'M', 0xE00D: 'N', 0xE00F: 'P', 0xE015: 'V',
    # 숫자 — 0xE033 + n 이 아니라 1~9 뒤에 0 이 온다 (0xE03D = 0)
    0xE034: '1', 0xE035: '2', 0xE036: '3', 0xE037: '4', 0xE038: '5',
    0xE039: '6', 0xE03A: '7', 0xE03B: '8', 0xE03C: '9', 0xE03D: '0',
    0xE042: '%', 0xE044: '(', 0xE045: ')', 0xE046: '−', 0xE047: '=', 0xE048: '+',
    0xE049: '[', 0xE04A: ']', 0xE04B: '{', 0xE04C: '}', 0xE04D: '|', 0xE04F: ':',
    0xE052: ',', 0xE053: '.', 0xE054: '≠', 0xE055: '<', 0xE056: '>',
    0xE06D: '/',                      # 분수 가로줄
    0xE0C8: '°',
    0xE0E5: 'a', 0xE0E6: 'b', 0xE0E7: 'c', 0xE0E8: 'd', 0xE0E9: 'e',
    0xE0EA: 'f', 0xE0EB: 'g', 0xE0EC: 'h', 0xE0EF: 'k',
    0xE0F1: 'm', 0xE0F2: 'n', 0xE0F4: 'p', 0xE0F5: 'q', 0xE0F8: 't',
    0xE0FC: 'x', 0xE0FD: 'y', 0xE0FE: 'z',
}

# 큰 괄호·묶음 조각 — 글자로 옮길 것이 없다(모양만 그리는 조각)
DROP = {0xE078, 0xE079, 0xE07A, 0xE07B,
        0xE100, 0xE101, 0xE102, 0xE103, 0xE104, 0xE105,
        0xE10A, 0xE10B, 0xE10C, 0xE10D}


def decode(ch: str) -> str:
    """수식 글자 하나를 보통 글자로. 모르면 '?' 를 돌려준다(나중에 눈으로 확인)."""
    o = ord(ch)
    if o < 0xE000 or o > 0xF8FF:
        return ch
    if o in DROP:
        return ''
    return EQ.get(o, '?')


def decode_text(s: str) -> str:
    return ''.join(decode(c) for c in s)
