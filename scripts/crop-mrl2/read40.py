"""뭉치 40개에 눈으로 붙인 숫자표. 섞인 뭉치는 「?」, 6·8 은 아직 못 가르니 「x」."""
MAP = {0: '0', 1: '1', 3: '3', 5: '2', 7: '2', 9: '5', 10: '9', 11: '0',
       12: '0', 13: '7', 14: '0', 15: '9', 18: '5', 22: '4', 23: 'x',
       26: '0', 27: 'x', 29: '7', 30: '?', 31: '0', 33: '7', 34: '1',
       36: '4', 37: '?', 39: '1', 20: '?'}


def digit(c):
    return MAP.get(int(c), '?')
